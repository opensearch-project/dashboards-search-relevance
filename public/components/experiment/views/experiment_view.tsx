import {
  EuiBadge,
  EuiButtonEmpty,
  EuiCallOut,
  EuiFlexGroup,
  EuiFlexItem,
  EuiLoadingSpinner,
  EuiPageHeader,
  EuiPageTemplate,
  EuiPanel,
  EuiSpacer,
  EuiText,
  EuiToolTip,
} from '@elastic/eui';
import React, { useEffect, useState } from 'react';
import { RouteComponentProps, withRouter } from 'react-router-dom';
import { CoreStart } from '../../../../../../src/core/public';
import {
  getExperimentDisplayName,
  isLikelyAutoGeneratedExperimentName,
} from '../../../../common';
import { ExperimentType } from '../../../types/index';
import { formatElapsedDuration } from '../../../utils/duration';
import { ExperimentService } from '../services/experiment_service';
import { useExperimentView } from '../hooks/use_experiment_view';
import { ExperimentEditMetadataModal } from './experiment_edit_metadata_modal';
import { PairwiseExperimentViewWithRouter } from './pairwise_experiment_view';
import { EvaluationExperimentViewWithRouter } from './evaluation_experiment_view';
import { HybridOptimizerExperimentViewWithRouter } from './hybrid_optimizer_experiment_view';

interface ExperimentViewProps extends RouteComponentProps<{ id: string }> {
  http: CoreStart['http'];
  notifications: CoreStart['notifications'];
  dataSourceId?: string | null;
}

// Ticks its own "Running for Xs" label once a second from mount to unmount, so only
// this leaf re-renders each second instead of the whole ExperimentView.
const ElapsedTimeLabel: React.FC<{ since: string }> = ({ since }) => {
  const [now, setNow] = useState(() => Date.now());

  useEffect(() => {
    const interval = setInterval(() => setNow(Date.now()), 1000);
    return () => clearInterval(interval);
  }, []);

  return (
    <p data-test-subj="experimentProcessingElapsed">
      Running for {formatElapsedDuration(now - new Date(since).getTime())}
    </p>
  );
};

export const ExperimentView: React.FC<ExperimentViewProps> = ({
  http,
  notifications,
  id,
  dataSourceId,
  history,
}) => {
  const { experiment, loading, error, refetch } = useExperimentView(http, id, dataSourceId);
  const [isEditOpen, setIsEditOpen] = useState(false);
  const experimentService = new ExperimentService(http);

  const pageTitle = experiment ? getExperimentDisplayName(experiment.name) : 'Experiment Details';
  const descriptionText =
    experiment &&
    typeof experiment.description === 'string' &&
    experiment.description.trim() !== ''
      ? experiment.description.trim()
      : undefined;

  const isProcessing = experiment?.status === 'PROCESSING';
  const showResults = Boolean(experiment) && !isProcessing;

  const editButton = (
    <EuiButtonEmpty
      iconType="pencil"
      disabled={isProcessing}
      onClick={() => setIsEditOpen(true)}
      data-test-subj="experimentEditMetadata"
    >
      Edit
    </EuiButtonEmpty>
  );

  return (
    <EuiPageTemplate paddingSize="l" restrictWidth="90%">
      <EuiPageHeader
        pageTitle={
          experiment ? (
            <EuiFlexGroup gutterSize="s" alignItems="center" responsive={false} wrap>
              <EuiFlexItem grow={false}>
                <span>{pageTitle}</span>
              </EuiFlexItem>
              {isLikelyAutoGeneratedExperimentName(experiment.name, experiment.type) && (
                <EuiFlexItem grow={false}>
                  <EuiToolTip content="This name was auto-generated. Click Edit to customize.">
                    <EuiBadge color="hollow">Auto</EuiBadge>
                  </EuiToolTip>
                </EuiFlexItem>
              )}
              <EuiFlexItem grow={false}>
                {isProcessing ? (
                  <EuiToolTip content="You cannot edit details while the experiment is processing.">
                    <span>{editButton}</span>
                  </EuiToolTip>
                ) : (
                  editButton
                )}
              </EuiFlexItem>
            </EuiFlexGroup>
          ) : (
            pageTitle
          )
        }
        description={descriptionText}
      />
      {!experiment && loading && (
        <>
          <EuiSpacer size="l" />
          <EuiText size="s" color="subdued" data-test-subj="experimentViewLoading">
            Loading experiment data...
          </EuiText>
        </>
      )}
      {!loading && error && (
        <>
          <EuiSpacer size="l" />
          <EuiCallOut
            title="Unable to load experiment"
            color="danger"
            iconType="alert"
            data-test-subj="experimentViewErrorCallOut"
          >
            <p>{error}</p>
          </EuiCallOut>
        </>
      )}
      {experiment && (
        <>
          <EuiSpacer size="s" />
          <EuiText size="s" color="subdued">
            Experiment ID: {experiment.id}
          </EuiText>
        </>
      )}
      {experiment && isProcessing && (
        <>
          <EuiSpacer size="l" />
          <EuiPanel
            hasBorder={false}
            hasShadow={false}
            paddingSize="l"
            style={{
              display: 'flex',
              justifyContent: 'center',
              alignItems: 'center',
              minHeight: '240px',
            }}
            data-test-subj="experimentProcessingPanel"
          >
            <EuiFlexGroup direction="column" alignItems="center" gutterSize="m">
              <EuiFlexItem grow={false}>
                <EuiLoadingSpinner size="xl" />
              </EuiFlexItem>
              <EuiFlexItem grow={false}>
                <EuiText textAlign="center">
                  <h3>Experiment is running</h3>
                  {experiment?.timestamp && <ElapsedTimeLabel since={experiment.timestamp} />}
                  <p>This page will update automatically once the experiment completes.</p>
                </EuiText>
              </EuiFlexItem>
            </EuiFlexGroup>
          </EuiPanel>
        </>
      )}
      {showResults && experiment.type === ExperimentType.PAIRWISE_COMPARISON && (
        <PairwiseExperimentViewWithRouter
          http={http}
          notifications={notifications}
          inputExperiment={experiment}
          history={history}
          dataSourceId={dataSourceId}
        />
      )}
      {showResults && experiment.type === ExperimentType.POINTWISE_EVALUATION && (
        <EvaluationExperimentViewWithRouter
          http={http}
          notifications={notifications}
          inputExperiment={experiment}
          history={history}
          dataSourceId={dataSourceId}
        />
      )}
      {showResults && experiment.type === ExperimentType.HYBRID_OPTIMIZER && (
        <HybridOptimizerExperimentViewWithRouter
          http={http}
          notifications={notifications}
          inputExperiment={experiment}
          history={history}
          dataSourceId={dataSourceId}
        />
      )}
      {experiment && (
        <ExperimentEditMetadataModal
          isOpen={isEditOpen}
          onClose={() => setIsEditOpen(false)}
          experimentId={experiment.id}
          initialName={experiment.name}
          initialDescription={experiment.description}
          dataSourceId={dataSourceId}
          experimentService={experimentService}
          onSaved={() => {
            notifications.toasts.addSuccess({
              title: 'Experiment details updated.',
            });
            refetch();
          }}
        />
      )}
    </EuiPageTemplate>
  );
};

export const ExperimentViewWithRouter = withRouter(ExperimentView);

export default ExperimentViewWithRouter;
